// Points the browser tab icon at the operator's tab and home-screen icon when one
// is set (Branding), else at the logo uploaded in Branding → Logo, and else at the
// stock icon. Called from the one place every surface
// adopts a StageState (use-stage-state.ts), exactly as applyAccentVar is, so the
// operator app and every kiosk display follow a logo change without a reload.
//
// The stored logo is already a square PNG: the Branding cropper always exports a
// square region, so there is nothing to letterbox. It may arrive as a
// /branding-images/ URL or a data URL; either works as an icon.
//
// PRECEDENCE. A custom icon wins over the logo, and the tab draws it itself from
// the icon's art, so the tab can differ from the home screen: the art is
// rasterised here over the icon's TAB background (Branding → Tab background),
// which is "none" by default, leaving just the art on the browser's tab strip.
// It is the home-screen sizes the server stores; the tab is never one of them.
// Only with no icon does the logo become the tab icon.
//
// RECOLOR. With "Recolor to match theme" on (the default) the app draws the logo
// as a CSS mask filled with the theme's foreground, because a single-colour logo
// is usually white artwork meant for the dark kiosk. A tab cannot use a mask, so
// the same recolouring is done once on a canvas: the art is rasterised and
// filled with the ink that contrasts with what it sits on, and the result is the
// tab icon. On a transparent tab that is the browser's colour scheme (white ink
// vanishes on a light tab strip); on a coloured tab it is that colour, whatever
// the scheme. With Recolor off the art is drawn as uploaded.

import { errorMessage } from "@main/services/errors";
import { logToServer } from "./client-log";
import { INK, iconInk, tabColor } from "./icon-ink";

/** The icon both HTML documents ship, and its declared type. Generated by
 *  scripts/build-icons.ts; apply-favicon.test.ts keeps the documents in step. */
export const STOCK_FAVICON = "/favicon.svg";
export const STOCK_FAVICON_TYPE = "image/svg+xml";

/** The declared type of a PNG: a recoloured or backed icon. A raw logo declares none (null). */
const PNG_TYPE = "image/png";

export { INK };

/** The tab's own icon: the art it is drawn from, and what it sits on (`#rrggbb`,
 *  or "none" for the art alone). */
export interface TabIcon {
  art: string;
  background: string;
}

const ICON_SIZE = 64;
/** The share of a backed tab icon its art fills; the rest is the background's margin. */
const BACKED_ART = 0.875;
/** The corner radius of a backed tab icon, as a share of its side. */
const BACKED_RADIUS = 0.19;
const DARK_SCHEME = "(prefers-color-scheme: dark)";

/**
 * Draws `src` and returns it as a PNG data URL: filled with `ink` unless that is
 * null (as uploaded), over a rounded square of `background` unless that is null.
 */
export type Rasterizer = (src: string, ink: string | null, background: string | null) => Promise<string>;

/** Rejects, rather than returning something plausible, when it cannot draw. */
const rasterizeInCanvas: Rasterizer = async (logo, ink, background) => {
  const canvas = document.createElement("canvas");
  canvas.width = ICON_SIZE;
  canvas.height = ICON_SIZE;
  // Before loading the image: with no 2D context there is nothing to wait for.
  const ctx = canvas.getContext("2d");
  if (!ctx) throw new Error("no 2D canvas context");
  const img = new Image();
  await new Promise<void>((resolve, reject) => {
    img.onload = () => resolve();
    img.onerror = () => reject(new Error("the logo image failed to load"));
    img.src = logo;
  });
  const w = img.naturalWidth || ICON_SIZE;
  const h = img.naturalHeight || ICON_SIZE;
  const room = background ? ICON_SIZE * BACKED_ART : ICON_SIZE;
  const scale = Math.min(room / w, room / h);
  // The art goes on a canvas of its own: tinting it in place would tint the
  // background drawn under it too.
  const art = document.createElement("canvas");
  art.width = ICON_SIZE;
  art.height = ICON_SIZE;
  const artCtx = art.getContext("2d");
  if (!artCtx) throw new Error("no 2D canvas context");
  artCtx.drawImage(img, (ICON_SIZE - w * scale) / 2, (ICON_SIZE - h * scale) / 2, w * scale, h * scale);
  if (ink) {
    // source-in keeps the art's alpha and replaces its colour: the same result
    // the CSS mask gives on the page.
    artCtx.globalCompositeOperation = "source-in";
    artCtx.fillStyle = ink;
    artCtx.fillRect(0, 0, ICON_SIZE, ICON_SIZE);
  }
  if (background) {
    ctx.fillStyle = background;
    ctx.beginPath();
    ctx.roundRect(0, 0, ICON_SIZE, ICON_SIZE, ICON_SIZE * BACKED_RADIUS);
    ctx.fill();
  }
  ctx.drawImage(art, 0, 0);
  return canvas.toDataURL("image/png");
};

// ── State ─────────────────────────────────────────────────────────────────────

let rasterize: Rasterizer = rasterizeInCanvas;
/** The latest thing asked for, so a scheme change can redo it. */
let request: { logo: string | null; monochrome: boolean; tab: TabIcon | null } = {
  logo: null,
  monochrome: false,
  tab: null,
};
/** Bumped whenever the answer changes; a slow raster only lands if still current. */
let seq = 0;
/** Key of the raster currently in flight, so a repeat broadcast does not start another. */
let inflight: string | null = null;
/** What was settled for an (ink, background, source). A failure carries the time it
 *  may be tried again; a success never expires. */
interface Entry {
  href: string;
  type: string | null;
  retryAt: number | null;
}
/** (ink, background, source) → its entry. Bounded: an icon changes rarely. */
const cache = new Map<string, Entry>();
export const CACHE_MAX = 4;
/**
 * How long a failed recolor stands before it is tried again. A dropped image
 * request should not cost the page its recolored icon for good, and an image that
 * will never decode should cost one attempt a minute, not one per broadcast.
 */
const FAILURE_RETRY_MS = 60_000;
/** Keys already reported, so retries of the same failure add no more lines. */
const warned = new Set<string>();
const WARNED_MAX = 16;
let scheme: MediaQueryList | null = null;

function prefersDark(): boolean {
  return scheme?.matches ?? false;
}

/** One listener for the page's life, started by the first call. */
function watchScheme(): void {
  if (scheme || typeof window.matchMedia !== "function") return;
  scheme = window.matchMedia(DARK_SCHEME);
  scheme.addEventListener("change", resolve);
}

/** The `<link rel="icon">` in the document head, created if a document has none. */
function iconLink(): HTMLLinkElement {
  const existing = document.head.querySelector<HTMLLinkElement>('link[rel="icon"]');
  if (existing) return existing;
  const link = document.createElement("link");
  link.rel = "icon";
  document.head.appendChild(link);
  return link;
}

/** `type` null is a logo exactly as uploaded: its format is whatever it is. */
function setIcon(href: string, type: string | null): void {
  const link = iconLink();
  // Called on every state broadcast. Re-assigning an identical href is not free:
  // some browsers refetch and repaint the tab icon for it.
  if (link.getAttribute("href") === href) return;
  // The stock icon is SVG and a recoloured one PNG, but a logo set through the API
  // may be any format, and a declared type that disagrees with the bytes makes a
  // browser skip the icon. A raw logo declares none, so the browser reads the
  // response.
  if (type === null) link.removeAttribute("type");
  else link.setAttribute("type", type);
  link.setAttribute("href", href);
}

/** Settle on an answer that needs no raster, and cancel any raster still loading. */
function settle(href: string, type: string | null): void {
  seq++;
  inflight = null;
  setIcon(href, type);
}

function resolve(): void {
  const { logo, monochrome, tab } = request;
  const source = tab?.art ?? logo;
  if (!source) return settle(STOCK_FAVICON, STOCK_FAVICON_TYPE);
  // A logo as uploaded needs no raster. The tab's art always has one, even
  // as uploaded: it is what finds out the stored file is gone (a restore that
  // carried the settings and not the images), which would otherwise be a blank tab.
  if (!tab && !monochrome) return settle(logo!, null);

  const background = tab ? tabColor(tab.background) : null;
  // On a colour the ink contrasts with the colour; on the tab strip, with the browser.
  const ink = background ? iconInk(background, monochrome) : monochrome ? (prefersDark() ? INK.dark : INK.light) : null;
  // What a failed draw falls back to: the logo as uploaded, or for the tab's own
  // art (which may be the very thing that failed to load) the stock icon.
  const fallback: Pick<Entry, "href" | "type"> = tab
    ? { href: STOCK_FAVICON, type: STOCK_FAVICON_TYPE }
    : { href: source, type: null };
  const key = `${ink}|${background}|${source}`;
  const hit = cache.get(key);
  // A failure inside its cool-down is still the answer; after it, it is tried again.
  if (hit && (hit.retryAt === null || Date.now() < hit.retryAt)) return settle(hit.href, hit.type);
  if (inflight === key) return;

  const token = ++seq;
  inflight = key;
  const remember = (entry: Entry) => {
    if (cache.size >= CACHE_MAX && !cache.has(key)) cache.clear();
    cache.set(key, entry);
    if (token !== seq) return; // a newer answer got here first
    inflight = null;
    setIcon(entry.href, entry.type);
  };
  rasterize(source, ink, background).then(
    (href) => remember({ href, type: PNG_TYPE, retryAt: null }),
    (err: unknown) => {
      // The tab still gets something, just not as intended. Said once per key
      // however many times it is retried, and sent to the server's log: a
      // console nobody has open is no evidence on a Sunday morning.
      if (!warned.has(key)) {
        if (warned.size >= WARNED_MAX) warned.clear();
        warned.add(key);
        logToServer(
          "branding",
          tab
            ? `the tab icon could not be drawn from the custom icon; using the built-in icon: ${errorMessage(err)}`
            : `the tab icon could not be recolored; using the logo as uploaded: ${errorMessage(err)}`,
        );
      }
      remember({ ...fallback, retryAt: Date.now() + FAILURE_RETRY_MS });
    },
  );
}

/**
 * Set the tab icon for the current branding.
 *
 * @param appLogo     The uploaded logo URL, or null for the stock icon.
 * @param monochrome  Recolor to match theme: tint the art to contrast with what it
 *                    sits on (the browser's colour scheme, or the tab's colour).
 *                    False leaves it as uploaded.
 * @param tab         The custom icon's art and tab background, or null for none.
 *                    When set it wins over the logo.
 */
export function applyFavicon(
  appLogo: string | null | undefined,
  monochrome?: boolean,
  tab?: TabIcon | null,
): void {
  request = { logo: appLogo || null, monochrome: !!monochrome, tab: tab?.art ? tab : null };
  watchScheme();
  resolve();
}

/** Test seam: forget everything, and swap the canvas for `fn` (null restores it). */
export function __resetForTests(fn: Rasterizer | null = null): void {
  scheme?.removeEventListener("change", resolve);
  scheme = null;
  request = { logo: null, monochrome: false, tab: null };
  seq++;
  inflight = null;
  cache.clear();
  warned.clear();
  rasterize = fn ?? rasterizeInCanvas;
}

/** Test seam: how many (ink, logo) results are held. */
export function __cacheSize(): number {
  return cache.size;
}
